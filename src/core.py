import os
from openai import OpenAI
from dotenv import load_dotenv

# 1. Загружаем переменные окружения из файла .env
load_dotenv()

# 2. Инициализируем клиент OpenAI
# Он автоматически возьмет ключ из переменной OPENAI_API_KEY
client = OpenAI()

def load_system_prompt(filepath="prompts/system_prompt.md"):
    """Читает системный промпт из файла."""
    try:
        with open(filepath, "r", encoding="utf-8") as file:
            return file.read()
    except FileNotFoundError:
        print(f"Ошибка: Файл {filepath} не найден. Убедитесь, что вы в корне проекта.")
        return None

def generate_summary(article_text):
    """
    Отправляет текст статьи в LLM и возвращает структурированный конспект.
    """
    system_prompt = load_system_prompt()
    if not system_prompt:
        return None

    print("⏳ Отправляем запрос в OpenAI... Пожалуйста, подождите.")
    
    try:
        # 3. Делаем запрос к API
        response = client.chat.completions.create(
            model="gpt-4o-mini", # Можно заменить на gpt-4o, если есть доступ
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": f"Вот текст научной статьи для конспектирования:\n\n{article_text}"}
            ],
            # 4. Настраиваем параметры (ВАЖНО: низкая температура для точности)
            temperature=0.1, 
            max_tokens=2000
        )
        
        # 5. Извлекаем и возвращаем текст ответа
        summary = response.choices[0].message.content
        return summary

    except Exception as e:
        print(f"❌ Произошла ошибка при запросе к API: {e}")
        return None

